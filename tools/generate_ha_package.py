def sensor(key, name, unit, dc, icon, kind, dec):
    r = "round(0) | int" if dec == 0 else f"round({dec})"
    null = "0" if kind == TOTAL else "{{ none }}"
    keep = "{% if this.state | is_number %}{{ this.state }}{% else %}{{ none }}{% endif %}"
    lines = [
        f"      - name: Health Hook {name}",
        f"        unique_id: health_hook_{key}",
        f"        unit_of_measurement: \"{unit}\"",
    ]
    if dc:
        lines.append(f"        device_class: {dc}")
    lines += [
        "        state_class: measurement",
        f"        icon: {icon}",
        "        state: >-",
        f"          {P}{{% set v = p.get('{key}') %}}",
        f"          {{% if '{key}' not in p %}}{keep}"
        f"{{% elif v is not none and v | is_number %}}{{{{ v | float | {r} }}}}{{% else %}}{null}{{% endif %}}",
    ]
    attrs = []
    if kind == LATEST:
        attrs.append(("measured_at", f"(p.get('dates') or {{}}).get('{key}')", key))
    if kind == DAY_AVG:
        attrs += [("min", "p.get('heart_rate_min')", "heart_rate_min"), ("max", "p.get('heart_rate_max')", "heart_rate_max")]
    if attrs:
        lines.append("        attributes:")
        for a, expr, k in attrs:
            lines.append(f"          {a}: >-\n            {P}{{{{ {expr} if '{k}' in p else this.attributes.get('{a}') }}}}")
    return "\n".join(lines)


FOOTER = f"""
      - name: Health Hook last sync
        unique_id: health_hook_last_sync
        device_class: timestamp
        icon: mdi:cellphone-arrow-down
        state: "{{{{ now().isoformat() }}}}"
        attributes:
          # Last payload without `days` (debugging)
          payload: "{{{{ trigger.event.data.data }}}}"
      - name: Health Hook app expiration
        unique_id: health_hook_app_expiration
        device_class: timestamp
        icon: mdi:timer-sand
        state: >-
          {P}
          {{% if p.get('expires_at') %}}{{{{ p.expires_at }}}}{{% elif this.state not in ['unknown', 'unavailable', '', none] %}}{{{{ this.state }}}}{{% else %}}{{{{ none }}}}{{% endif %}}
"""

PACKAGE = Path(__file__).resolve().parent.parent / "homeassistant" / "packages" / "health_hook.yaml"


def render():
    return HEADER + "\n".join(sensor(*m) for m in METRICS) + "\n" + FOOTER


if __name__ == "__main__":
    out = render()
    if "--check" in sys.argv:
        if PACKAGE.read_text(encoding="utf-8") != out:
            sys.exit(f"{PACKAGE.name} is out of date: run python3 tools/generate_ha_package.py and commit it")
        print(f"{PACKAGE.name} is up to date")
    else:
        PACKAGE.write_text(out, encoding="utf-8")
        print(f"{PACKAGE}: {len(METRICS)} metric sensors")
